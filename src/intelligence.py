"""MosquiTech Intelligence: a grounded LLM assistant for public-health officers.

Design (easy to explain to judges):
  1. build_context()  - collect REAL numbers: ML forecasts + risk tiers, observed history, weather, vulnerability,
                        Shapley explanation, ward ranking, model accuracy, seasonal history. No LLM involved.
  2. ask()            - send that context + the officer's question to Gemini with strict rules (SYSTEM_PROMPT).
  3. The LLM only EXPLAINS. It never computes predictions and cannot change the ML risk tier, which is fixed in
     the context. If the API is missing or fails, the dashboard shows an error - it never invents an answer.
  4. evidence_brief() - a deterministic, rule-based summary of the same context (works with no API key).
"""
